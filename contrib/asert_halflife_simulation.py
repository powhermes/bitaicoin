def report_surge_scenarios():
    print("=" * 100)
    print("SURGE-THEN-REVERT: 1x -> Kx for N blocks -> back to 1x. Recovery measured in")
    print("blocks/hours AFTER the surge ends (not from t=0).")
    print("=" * 100)
    header = f"{'half-life':<10}{'surge':<8}{'held (blk)':<12}{'recover (blk)':<16}{'recover (h)':<13}{'worst instant mult during transition':<40}"
    print(header)
    print("-" * len(header))
    for hl_name, hl in HALF_LIVES.items():
        for surge_k in (10, 100, 1000):
            for held in (20, 100, 500):
                schedule, max_blocks = surge_then_revert(surge_k, held)
                log = run_deterministic(hl, schedule, max_blocks)
                settle_blocks, worst = measure_recovery(log, shock_end_height=held)
                if settle_blocks is not None:
                    # wall-clock hours for those recovery blocks, post-shock
                    t_shock_end = log[held - 1]["time"]
                    t_settle = log[held - 1 + settle_blocks + 19]["time"] if held - 1 + settle_blocks + 19 < len(log) else None
                    hrs = f"{(t_settle - t_shock_end) / 3600.0:.1f}" if t_settle is not None else "n/a"
                else:
                    hrs = "n/a"
                sb = str(settle_blocks) if settle_blocks is not None else "n/a(>tail)"
                print(f"{hl_name:<10}{str(surge_k)+'x':<8}{held:<12}{sb:<16}{hrs:<13}{f'{worst:.1f}x':<10}")
        print()


def report_pool_hopping():
    print("=" * 100)
    print("POOL-HOPPING: alternating on_k for `on` blocks / 1x for `off` blocks, repeated.")
    print("Reports worst instantaneous rate ratio seen across all cycles, and whether")
    print("difficulty ever fully re-settles to 1x during the `off` phases.")
    print("=" * 100)
    header = f"{'half-life':<10}{'on_k':<8}{'on/off (blk)':<14}{'cycles':<8}{'worst instant mult':<20}{'ever resettles off-phase':<26}"
    print(header)
    print("-" * len(header))
    for hl_name, hl in HALF_LIVES.items():
        for on_k, on_blocks, off_blocks, cycles in [(10, 50, 50, 6), (100, 20, 100, 4), (1000, 10, 200, 3)]:
            schedule, max_blocks = pool_hopping(on_k, on_blocks, off_blocks, cycles)
            log = run_deterministic(hl, schedule, max_blocks)
            worst = max(e["rate_ratio"] if e["rate_ratio"] >= 1 else 1.0 / e["rate_ratio"] for e in log)
            # check whether, at the END of any off-phase, rate_ratio was within 10% of 1.0
            period = on_blocks + off_blocks
            resettled_any_off_phase = False
            for cyc in range(cycles):
                off_end_h = cyc * period + on_blocks + off_blocks
                if off_end_h <= len(log):
                    e = log[off_end_h - 1]
                    if abs(e["rate_ratio"] - 1.0) <= 0.10:
                        resettled_any_off_phase = True
            print(f"{hl_name:<10}{str(on_k)+'x':<8}{f'{on_blocks}/{off_blocks}':<14}{cycles:<8}{f'{worst:.1f}x':<20}{'yes' if resettled_any_off_phase else 'no':<26}")
        print()


def report_stochastic():
    print("=" * 100)
    print("STOCHASTIC (Poisson-arrival) vs DETERMINISTIC: 100x surge held 100 blocks then")
    print("revert to 1x. 5 random seeds per half-life.")
    print()
    print("First pass used the deterministic report's strict per-block metric (20")
    print("CONSECUTIVE individual blocks each within 10% of target) on the stochastic")
    print("logs too, and it returned None for every single seed at every half-life --")
    print("investigated rather than dismissed: a Poisson arrival process has per-block")
    print("coefficient of variation = 1.0 (stdev == mean for Exponential), so individual")
    print("blocks routinely land 2-5x off the mean by honest chance alone, making 20-in-a-row")
    print("within 10% essentially unsatisfiable regardless of half-life. That's a real")
    print("property of the metric, not of the DAA -- so a rolling-window metric (below)")
    print("is used instead, since it's what a halflife-scale DAA response actually operates on.")
    print("=" * 100)
    header = f"{'half-life':<10}{'seed':<6}{'strict recover':<16}{'windowed recover':<18}{'worst instant mult':<20}"
    print(header)
    print("-" * len(header))
    for hl_name, hl in HALF_LIVES.items():
        schedule, max_blocks = surge_then_revert(100, 100)
        det_log = run_deterministic(hl, schedule, max_blocks)
        det_settle, det_worst = measure_recovery(det_log, shock_end_height=100)
        det_settle_w = measure_recovery_windowed(det_log, shock_end_height=100)
        print(f"{hl_name:<10}{'(det)':<6}{str(det_settle):<16}{str(det_settle_w):<18}{f'{det_worst:.1f}x':<20}")
        settles_strict, settles_windowed = [], []
        for seed in range(5):
            rng = random.Random(seed)
            log = run_stochastic(hl, schedule, max_blocks, rng)
            settle, worst = measure_recovery(log, shock_end_height=100)
            settle_w = measure_recovery_windowed(log, shock_end_height=100)
            settles_strict.append(settle)
            settles_windowed.append(settle_w)
            print(f"{'':<10}{seed:<6}{str(settle):<16}{str(settle_w):<18}{f'{worst:.1f}x':<20}")
        valid_w = [s for s in settles_windowed if s is not None]
        if valid_w:
            print(f"{'':<10}{'spread(w)':<6}min={min(valid_w)} max={max(valid_w)} mean={sum(valid_w)/len(valid_w):.0f}")
        print()


def report_mtp_impact():
    print("=" * 100)
    print("MTP-FLOOR IMPACT: how often the real MTP-floor constraint (nTime >")
    print("median of previous 11 blocks) actually binds during the sharpest, most")
    print("sustained bursts (short 20-block surges above showed 0/3020 -- not sustained")
    print("or extreme enough for the DAA to have eased the target far before the surge")
    print("ends; these scenarios hold the surge much longer to actually probe the floor).")
    print("=" * 100)
    header = f"{'half-life':<10}{'scenario':<28}{'blocks MTP-clamped':<20}{'of total':<10}"
    print(header)
    print("-" * len(header))
    for hl_name, hl in HALF_LIVES.items():
        for surge_k, held in [(1000, 500), (1000, 2000), (10000, 500)]:
            schedule, max_blocks = surge_then_revert(surge_k, held)
            log = run_deterministic(hl, schedule, max_blocks)
            clamped_during_surge = sum(1 for e in log if e["mtp_clamped"] and e["h"] <= held)
            print(f"{hl_name:<10}{f'{surge_k}x/{held}blk surge':<28}{clamped_during_surge:<20}{clamped_during_surge}/{held}")
    print()


if __name__ == "__main__":
    report_surge_scenarios()
    report_pool_hopping()
    report_stochastic()
    report_mtp_impact()
    print("No half-life is selected by this script. Comparison only, per explicit instruction.")
